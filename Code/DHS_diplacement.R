# Function to compute TT weighted mean and other summary statistics from a single country-polygon (with correction for unpopulated cells)
compute_weighted_mean <- function(polygon, travel_time_raster, pop_raster) {
  # Extract the weights (population values) for the current polygon
  weights_values <- exact_extract(pop_raster, polygon)

  # If all weights are NA for this polygon, create a temporary raster with values set to 1
  if (all(is.na(weights_values[[1]]$value))) {
    tmp_raster <- pop_raster
    tmp_raster[] <- 1
    weights_raster <- tmp_raster
  } else {
    weights_raster <- pop_raster
  }

  # Compute the weighted mean using the chosen weights raster
  result <- exact_extract(travel_time_raster, polygon,
    # A) For weight with population raster use like : "exact_extract(rast, poly, 'weighted_mean', weights=weights)" )
    # B)In all of the summary operations, NA values in the the primary raster (x) raster are ignored (i.e., na.rm = TRUE.) If NA values occur
    # in the weighting raster, the result of the weighted operation will be NA. NA values in both x and weights can be replaced on-the-fly using
    # the default_value and default_weight arguments.
    fun = c("mean", "min", "max", "mode", "median", "sum", "mean", "weighted_mean"),
    weights = weights_raster,
    default_weight = 0,
    append_cols = c("LONGNUM", "LATNUM", "place_of_residence", "CountryName"),
    progress = TRUE
  )

  return(result)
}

# Function that run compute_weighted_mean function across all country-polygons from a same country and append results
extract_travel_time <- function(country_name, travel_time_raster, pop_raster, extract_table) {
  # Check CRS before reprojection
  print("Check CRS before reprojection")
  print(extract_table)
  print(travel_time_raster)
  print(pop_raster)

  # Filter for DHS in the specified country and reproject to the travel time raster CRS
  extract_table_pr <- extract_table[extract_table$CountryName == country_name, ] # The bug is here "Sierra Leone" is not detected
  extract_table_pr <- project(extract_table_pr, travel_time_raster) # Can be improve condition that stop script if crs of extract_table_pr, travel_time_raster and pop_raster are different

  # Check CRS after reprojection
  print("Check CRS after reprojection")
  print(extract_table_pr)
  print(travel_time_raster)
  print(pop_raster)

  # Convert into sf, sfc, SpatialPolygonsDataFrame, or SpatialPolygons as exact_extract want this format
  extract_table_pr_sf <- st_as_sf(extract_table_pr)

  # Loop through each row (i.e., each polygon) in extract_table_pr_sf to compute summary stat and TT pop weighted mean
  results <- lapply(1:nrow(extract_table_pr_sf), function(i) {
    compute_weighted_mean(extract_table_pr_sf[i, ], travel_time_raster, pop_raster)
  })

  # Bind results together
  extract_result <- bind_rows(results)


  return(extract_result)
}

# Function to compute TT pop weighted median (with correction for unpopulated cells)
TT_pop_weighted_median <-
  function(polygon, travel_time_raster, pop_raster) {
    result_median <- exact_extract(
      travel_time_raster,
      polygon,
      fun = function(values, coverage_frac, weights) {
        # If all weights are zero, assume each weight is 1
        # Because with  default_weight = 0,  when there is no population at all in the buffer, it take the smallest TT pixel value in the buffer because we ordered the value before and cum_weighted_coverage_frac never increases and
        # is always equals to 0. Therefore, the first element of cum_weighted_coverage_frac is >= to total_weighted_coverage_frac as 0>=0 is TRUE.  We want to avoid that
        if (all(weights == 0)) {
          weights <- rep(1, length(values))
        }

        # Ensure the data is ordered by the values
        ord <-
          order(values, na.last = NA) # na.last is set by default to TRUE and in this case, missing values in the data are put last. This biased the median when we have population that fall in water with NA in TT. Therefore  I set na.last = NA which remove missing values
        values <- values[ord]
        weighted_coverage_frac <- coverage_frac * weights
        weighted_coverage_frac <- weighted_coverage_frac[ord]

        # Compute the cumulative sum of weighted_coverage_frac
        cum_weighted_coverage_frac <- cumsum(weighted_coverage_frac)
        total_weighted_coverage_frac <- sum(weighted_coverage_frac)

        # Find where the cumulative weight surpasses half of the total weight (show row numbers where we are over 0.5 of the total weight and select the first row number)
        idx <-
          which(cum_weighted_coverage_frac >= total_weighted_coverage_frac / 2)[1]

        # Return the weighted median
        return(values[idx])
      },
      weights = pop_raster,
      # When default_weight = 0 is not set, anytime there is at least one NA in the pop raster within the buffer, the median TT will be NA
      default_weight = 0,
      append_cols = c("LONGNUM", "LATNUM", "place_of_residence", "CountryName")
    )

    return(result_median)
  }


