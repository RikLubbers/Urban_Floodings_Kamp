# Create extraction table listing Country code, Country name, epsg_code, Travel time files names and population raster files names
# Download and list of country name and their projection
download.file("https://github.com/fleurhierink/Population_Access/raw/main/data/raw/projections/projections.xlsx", "data/processed/Travel_times_projection_list/projections.xlsx")
projections <- read_excel("data/processed/Travel_times_projection_list/projections.xlsx")

# Filter for relevant countries that in the DHS
country_list <- sort(unique(extract_table_bf_rr_ub$CountryName))

# Create a table with the relevant countries along with their country code and epsg_code
country_table <- projections %>%
  filter(country %in% country_list | country_code %in% c("SLE", "ZAF")) #  # South Africa and Sierra Leone dont match when I use merge because they are composed of two words

# Attach the country name to the corresponding travel raster
travel_time_files <- list.files("data/processed/rTravel_times/") %>%
  as.data.frame() %>%
  rename(travel_time_files = ".") %>%
  mutate(country_code = str_replace_all(travel_time_files, c("travel_time_" = "", ".tif" = ""))) # I get the raster file names  and country code until here

# Attach the country name to the corresponding population raster
pop_raster_files <- pop_raster_files <- list.files("data/raw/worldpop/worldpop_constrained/") %>%
  as.data.frame() %>%
  rename(pop_raster_files = ".") %>%
  mutate(country_code = str_replace_all(pop_raster_files, c("rPopulation_" = "", ".tif" = ""))) # I get the raster file names  and country code until here

# Merge travel time raster, pop raster and table with relevant countries along their country code and epsg_code
travel_time_pop_epsg_files <- country_table %>%
  left_join(travel_time_files, by = "country_code") %>% #  I merge the latter with country names
  left_join(pop_raster_files, by = "country_code") %>%
  sort("country")

# Attach the country name from country_list because Sierra Lenoe and South Africa are filtered properly only in the object
travel_time_pop_epsg_files <- cbind(travel_time_pop_epsg_files, country_list)



################################################################
# Sequential extraction process using a loop over the extraction table
################################################################

# Initialize an empty list to store the results
travel_time_extr_list <- list()
travel_time_extr_median_list <- list()


# Loop over the extract table that record travel time and pop raster file paths and corresponding country names
for (i in 1:nrow(travel_time_pop_epsg_files)) {
  # Set file names to read
  travel_time_file_name <- travel_time_pop_epsg_files$travel_time_files[i]
  pop_raster_file_name <- travel_time_pop_epsg_files$pop_raster_files[i]
  country_name <- travel_time_pop_epsg_files$country_list[i]

  # Import travel time raster
  travel_time_raster <- rast(paste0("data/processed/rTravel_times/", travel_time_file_name))

  # Import population raster
  pop_raster <- rast(paste0("data/raw/worldpop/worldpop_constrained/", pop_raster_file_name))

  # Extract travel time statistics for the current country
  extract_result <- extract_travel_time(country_name, travel_time_raster, pop_raster, extract_table_bf_rr_ub) # With this function the travel time computed for  the country is only used => question to fleur => some pixel crosss national border
  # Append the result to its respective list
  travel_time_extr_list[[i]] <- extract_result

  # Extract weighted median travel time for the current country
  extract_result_median <- extract_travel_time_median(country_name, travel_time_raster, pop_raster, extract_table_bf_rr_ub)
  # Append the result to its respective list
  travel_time_extr_median_list[[i]] <- extract_result_median

  # Remove travel time and population raster
  rm(travel_time_raster, pop_raster)
}


# Append travel time results of all countries in one table and rename variable
travel_time_extr <- do.call(rbind, travel_time_extr_list) %>%
